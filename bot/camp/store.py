"""每個聊天室一份露營計畫，state 以 JSON 存。

有 DATABASE_URL（Render Postgres）就用 Postgres；否則用 SQLite（本機與測試）。
測試若設了 CAMP_DB，一律走 SQLite，避免連到真正的資料庫。
"""
import json
import os
import sqlite3
import time

BASE = os.path.join(os.path.dirname(__file__), "..", "..", "data")
DB_PATH = os.environ.get("CAMP_DB", os.path.abspath(os.path.join(BASE, "camp.db")))


def _camp_db():
    return (os.environ.get("CAMP_DB") or "").strip()


def _database_url():
    return (os.environ.get("DATABASE_URL") or "").strip()


def backend(path=None):
    """sqlite 或 postgres。明示路徑與 CAMP_DB 都算 sqlite。"""
    if path or _camp_db():
        return "sqlite"
    if _database_url():
        return "postgres"
    return "sqlite"


def _sqlite_path(path=None):
    return path or _camp_db() or DB_PATH


def _pg_dsn(url):
    if url.startswith("postgres://"):
        return "postgresql://" + url[len("postgres://"):]
    return url


class Conn:
    """sqlite3 / psycopg 的小包裝。? 佔位符兩邊都吃，離開 with 會提交並關閉。"""

    def __init__(self, raw, pg):
        self.raw = raw
        self.pg = pg

    def execute(self, sql, params=()):
        if self.pg:
            sql = sql.replace("?", "%s")
        cur = self.raw.cursor()
        cur.execute(sql, params)
        return cur

    def commit(self):
        self.raw.commit()

    def close(self):
        self.raw.close()

    def __enter__(self):
        return self

    def __exit__(self, exc_type, exc, tb):
        try:
            if exc_type:
                self.raw.rollback()
            else:
                self.raw.commit()
        finally:
            self.raw.close()
        return False


def _ensure(conn):
    if conn.pg:
        conn.execute("""CREATE TABLE IF NOT EXISTS plans(
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            chat_id TEXT NOT NULL,
            status TEXT NOT NULL,
            state TEXT NOT NULL,
            created DOUBLE PRECISION,
            updated DOUBLE PRECISION)""")
        conn.execute("""CREATE TABLE IF NOT EXISTS chat_log(
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            chat_id TEXT NOT NULL,
            role TEXT NOT NULL,
            content TEXT NOT NULL)""")
    else:
        conn.execute("""CREATE TABLE IF NOT EXISTS plans(
            id INTEGER PRIMARY KEY AUTOINCREMENT, chat_id TEXT NOT NULL,
            status TEXT NOT NULL, state TEXT NOT NULL, created REAL, updated REAL)""")
        conn.execute("""CREATE TABLE IF NOT EXISTS chat_log(
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            chat_id TEXT NOT NULL,
            role TEXT NOT NULL,
            content TEXT NOT NULL)""")
    conn.execute("CREATE INDEX IF NOT EXISTS ix_chat ON plans(chat_id, status)")
    conn.execute("CREATE INDEX IF NOT EXISTS ix_chat_log ON chat_log(chat_id, id)")


def _open_sqlite(path):
    folder = os.path.dirname(path)
    if folder:
        os.makedirs(folder, exist_ok=True)
    raw = sqlite3.connect(path, timeout=10)
    return Conn(raw, pg=False)


def _open_postgres(url):
    import psycopg
    raw = psycopg.connect(_pg_dsn(url), connect_timeout=10, application_name="xiaoguitou")
    return Conn(raw, pg=True)


def connect(path=None):
    if backend(path) == "postgres":
        conn = _open_postgres(_database_url())
    else:
        conn = _open_sqlite(_sqlite_path(path))
    try:
        _ensure(conn)
        conn.commit()
    except Exception:
        conn.close()
        raise
    return conn


def ensure_schema():
    """開機時建表。連線失敗就讓程序起不來，避免默默寫進會被清掉的 SQLite。"""
    with connect():
        return backend()


def new_state(name, organizer_id, organizer_name):
    return {"name": name, "organizer": organizer_id, "organizer_name": organizer_name,
            "candidates": [], "members": {}, "wishes": [], "area": "",
            "phase": "planning", "options": [], "option_votes": {}, "chosen": None}


class Store:
    def __init__(self, path=None):
        self.path = path

    def _c(self):
        return connect(self.path)

    def active(self, chat_id):
        with self._c() as c:
            row = c.execute("SELECT id, state FROM plans WHERE chat_id=? AND status='active' "
                            "ORDER BY id DESC LIMIT 1", (chat_id,)).fetchone()
        return (row[0], json.loads(row[1])) if row else (None, None)

    def create(self, chat_id, state):
        now = time.time()
        payload = json.dumps(state, ensure_ascii=False)
        with self._c() as c:
            if c.pg:
                row = c.execute(
                    "INSERT INTO plans(chat_id,status,state,created,updated) VALUES(?,?,?,?,?) RETURNING id",
                    (chat_id, "active", payload, now, now)).fetchone()
                return row[0]
            cur = c.execute(
                "INSERT INTO plans(chat_id,status,state,created,updated) VALUES(?,?,?,?,?)",
                (chat_id, "active", payload, now, now))
            return cur.lastrowid

    def save(self, plan_id, state):
        with self._c() as c:
            c.execute("UPDATE plans SET state=?, updated=? WHERE id=?",
                      (json.dumps(state, ensure_ascii=False), time.time(), plan_id))

    def close(self, plan_id, status="closed"):
        with self._c() as c:
            c.execute("UPDATE plans SET status=?, updated=? WHERE id=?", (status, time.time(), plan_id))
